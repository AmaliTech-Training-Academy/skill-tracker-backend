package com.amalitech.analytics.service.model.enums;

public enum GoalType {
    /**
     * Goal to reach a specific total XP in a skill.
     */
    TARGET_XP,
    /**
     * Goal to complete a specific number of tasks in a skill.
     */
    TASKS_COMPLETED,
    /**
     * Goal to reach a specific XP threshold corresponding to a level.
     */
    REACH_LEVEL
}